/**
 * Unit Tests for upsert (client method) against a fake SAP
 *
 * - Wave order: function group includes → main program → modules → domains → data elements → rest
 * - Generated L<group>UXX is refused; an .asinc named like a group include gets a hint
 * - A group created for the batch is reported created (with the .asfugr file's description)
 * - populateAfterCreate: stateless POST → lock → PUT(s) → unlock, unlocking on PUT failure
 * - A lock object whose populate failed is a shell the next upsert updates
 * - A message class whose second PUT fails reports what was saved, and still unlocks
 */

import { describe, it, expect } from 'bun:test';
import * as fs from 'fs';
import * as path from 'path';
import { upsert } from '../../client/methods/craud/upsert';
import { getFormHandler } from '../../core/forms';
import { fakeSap, isCreate, isLock, isUnlock, loggedIn } from './fakeSap';
import type { Call } from './fakeSap';

const FIXTURES = path.join(import.meta.dir, '../fixtures');

function fixture(name: string): string {
    return fs.readFileSync(path.join(FIXTURES, name), 'utf8');
}

function createdName(call: Call): string {
    return /adtcore:name="([^"]+)"/.exec(call.body ?? '')?.[1] ?? '?';
}

describe('upsert wave order', () => {
    it('writes group includes, the main program, modules, domains, data elements, then the rest', async () => {
        const sap = fakeSap();
        const [results, error] = await upsert(loggedIn(), sap.requestor, [
            { name: 'ZCL_LAST', extension: 'aclass', content: 'CLASS zcl_last DEFINITION. ENDCLASS.' },
            { name: 'ZSNAP_CHAR1', extension: 'asdtel', content: fixture('ddic/zsnap_char1.asdtel') },
            { name: 'Z_FM', extension: 'asfunc', container: 'ZFG', content: 'FUNCTION z_fm. ENDFUNCTION.' },
            { name: 'ZSNAP_SIGNAGE', extension: 'asdoma', content: fixture('ddic/zsnap_signage.asdoma') },
            { name: 'ZFG', extension: 'asfugr', content: 'FUNCTION-POOL zfg.', description: 'My group' },
            { name: 'LZFGF01', extension: 'asfinc', container: 'ZFG', content: '* forms' },
        ], '$TMP');

        expect(error).toBeNull();
        expect(sap.calls.filter(isCreate).map(createdName)).toEqual(['ZFG', 'LZFGF01', 'Z_FM', 'ZSNAP_SIGNAGE', 'ZSNAP_CHAR1', 'ZCL_LAST']);

        // The main program is written after the include is created and before the module.
        const puts = sap.calls.filter(call => call.method === 'PUT').map(call => call.path);
        expect(puts).toEqual([
            '/sap/bc/adt/functions/groups/zfg/includes/lzfgf01/source/main',
            '/sap/bc/adt/functions/groups/zfg/source/main',
            '/sap/bc/adt/functions/groups/zfg/fmodules/z_fm/source/main',
            '/sap/bc/adt/oo/classes/zcl_last/source/main',
        ]);

        // The group is created with its file's description and reported created, not updated.
        expect(sap.calls.find(isCreate)!.body).toContain('adtcore:description="My group"');
        expect(results!.find(r => r.name === 'ZFG')!.status).toBe('created');
        expect(results!.every(r => r.status === 'created')).toBe(true);
    });

    it('reports a group created only as a container first', async () => {
        const sap = fakeSap();
        const [results] = await upsert(loggedIn(), sap.requestor, [{ name: 'LZNEWF01', extension: 'asfinc', container: 'ZNEW', content: '* x' }], '$TMP');

        expect(results!.map(r => [r.name, r.extension, r.status])).toEqual([['ZNEW', 'asfugr', 'created'], ['LZNEWF01', 'asfinc', 'created']]);
        expect(sap.calls.find(isCreate)!.body).toContain('adtcore:description="Function group ZNEW"');
    });
});

describe('upsert function group guards', () => {
    it('refuses the generated L<group>UXX include before sending anything', async () => {
        const sap = fakeSap();
        const [, error] = await upsert(loggedIn(), sap.requestor, [{ name: 'LZFGUXX', extension: 'asfinc', container: 'ZFG', content: '' }], '$TMP');

        expect(error?.message).toContain('generated by SAP');
        expect(sap.calls).toHaveLength(0);
    });

    it('hints that an .asinc named like a group include should be an .asfinc', async () => {
        const sap = fakeSap([call => (isCreate(call) ? new Response('<exc:exception xmlns:exc="x"><localizedMessage>This syntax cannot be used for an object name</localizedMessage></exc:exception>', { status: 400 }) : null)]);
        const [, error] = await upsert(loggedIn(), sap.requestor, [{ name: 'LZFGF01', extension: 'asinc', content: '* x' }], '$TMP');

        expect(error?.message).toContain('save it as lzfgf01.asfinc');
    });
});

const MSAG_SOURCE = `{
  "description": "Catalyst test MC v2",
  "messages": [
    { "number": "001", "text": "First", "selfExplanatory": true }
  ]
}
`;

describe('populateAfterCreate (message class)', () => {
    it('creates statelessly, then locks, reads, PUTs and unlocks', async () => {
        const sap = fakeSap([
            call => (call.method === 'GET' && call.path === '/sap/bc/adt/messageclass/zmc' && sap.calls.some(isCreate) ? new Response(fixture('msag/message-class.xml').replace(/<mc:messages[\s\S]*<\/mc:messages>/, ''), { status: 200 }) : null),
        ]);
        const [results, error] = await upsert(loggedIn(), sap.requestor, [{ name: 'ZMC', extension: 'asmsag', content: MSAG_SOURCE }], '$TMP');

        expect(error).toBeNull();
        expect(results![0]!.status).toBe('created');
        const create = sap.calls.find(isCreate)!;
        expect(create.headers['X-sap-adt-sessiontype']).toBe('stateless');

        const steps = sap.calls.slice(sap.calls.indexOf(create) + 1).map(call => (isLock(call) ? 'LOCK' : isUnlock(call) ? 'UNLOCK' : call.method));
        expect(steps).toEqual(['LOCK', 'GET', 'PUT', 'UNLOCK']);
    });

    it('unlocks when the PUT fails', async () => {
        const sap = fakeSap([
            call => (call.method === 'GET' && call.path === '/sap/bc/adt/messageclass/zmc' && sap.calls.some(isCreate) ? new Response(fixture('msag/message-class.xml'), { status: 200 }) : null),
            call => (call.method === 'PUT' ? new Response('<exc:exception xmlns:exc="x"><localizedMessage>Boom</localizedMessage></exc:exception>', { status: 500 }) : null),
        ]);
        const [, error] = await upsert(loggedIn(), sap.requestor, [{ name: 'ZMC', extension: 'asmsag', content: MSAG_SOURCE }], '$TMP');

        expect(error?.message).toContain('Boom');
        expect(sap.calls.at(-1)!.params['_action']).toBe('UNLOCK');
    });
});

describe('populateAfterCreate (lock object)', () => {
    const fullDocument = fixture('enqu/ezsnap_tab.xml');
    const shell = fullDocument.replaceAll('<enqu:parameterWanted>true', '<enqu:parameterWanted>false');
    const [local] = getFormHandler('asenqu')!.toSource(fullDocument);
    const name = /adtcore:name="([^"]+)"/.exec(fullDocument)![1]!;
    const uri = `/sap/bc/adt/ddic/lockobjects/sources/${name.toLowerCase()}`;

    it('leaves a shell on a failed populate that the next upsert updates (not unchanged)', async () => {
        let created = false;
        let failPut = true;
        const sap = fakeSap([
            call => {
                if (isCreate(call)) { created = true; return new Response('', { status: 201 }); }
                return null;
            },
            call => (call.method === 'GET' && call.path === uri ? (created ? new Response(shell, { status: 200 }) : new Response('', { status: 404 })) : null),
            call => (call.method === 'PUT' && failPut ? new Response('<exc:exception xmlns:exc="x"><localizedMessage>Table locked</localizedMessage></exc:exception>', { status: 500 }) : null),
        ]);

        const [, firstErr] = await upsert(loggedIn(), sap.requestor, [{ name, extension: 'asenqu', content: local! }], '$TMP');
        expect(firstErr?.message).toContain('Table locked');
        expect(sap.calls.at(-1)!.params['_action']).toBe('UNLOCK');

        failPut = false;
        const [results, secondErr] = await upsert(loggedIn(), sap.requestor, [{ name, extension: 'asenqu', content: local! }], '$TMP');
        expect(secondErr).toBeNull();
        expect(results![0]!.status).toBe('updated');
    });
});

describe('message class multi-PUT partial failure', () => {
    it('says what was saved when the create PUT fails, and unlocks', async () => {
        const server = fixture('msag/message-class.xml');
        const sap = fakeSap([
            call => (call.method === 'GET' && call.path === '/sap/bc/adt/messageclass/zcatalyst_test_mc' ? new Response(server, { status: 200 }) : null),
            call => (call.method === 'PUT' && sap.calls.filter(c => c.method === 'PUT').length === 2 ? new Response('<exc:exception xmlns:exc="x"><localizedMessage>Number 004 rejected</localizedMessage></exc:exception>', { status: 500 }) : null),
        ]);
        const source = `{
  "description": "Catalyst test MC v3",
  "messages": [
    { "number": "001", "text": "Changed", "selfExplanatory": true },
    { "number": "004", "text": "New", "selfExplanatory": true }
  ]
}
`;
        const [, error] = await upsert(loggedIn(), sap.requestor, [{ name: 'ZCATALYST_TEST_MC', extension: 'asmsag', content: source }], '$TMP');

        expect(error?.message).toContain('was partially updated');
        expect(error?.message).toContain('saved description, changed and deleted messages');
        expect(error?.message).toContain('not saved: new messages 004');
        expect(error?.message).toContain('Number 004 rejected');
        expect(sap.calls.at(-1)!.params['_action']).toBe('UNLOCK');
    });
});
