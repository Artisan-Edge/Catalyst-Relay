/**
 * Upsert Rules — how function group parts are ordered, refused and explained on write
 */

import type { Result } from '../../../types/result';
import { ok, err } from '../../../types/result';
import type { ObjectRef } from '../../../types/requests';
import { OBJECT_CONFIG_MAP } from '../types';
import { FUNCTION_GROUP, FUNCTION_GROUP_INCLUDE, FUNCTION_MODULE, containerFromIncludeName, isFunctionGroupInclude, isGeneratedInclude } from './names';

const PROGRAM_INCLUDE = OBJECT_CONFIG_MAP.asinc;

/**
 * Upsert order of function group parts: includes, then the main program (written after the
 * includes so the file wins over the INCLUDE lines SAP appends when one is created), then modules
 */
export const FUNCTION_GROUP_UPSERT_ORDER: readonly string[] = [FUNCTION_GROUP_INCLUDE.extension, FUNCTION_GROUP.extension, FUNCTION_MODULE.extension];

/**
 * Refuse writing L<group>UXX: SAP generates it from the group's function modules
 */
export function refuseGeneratedInclude(object: ObjectRef): Result<void, Error> {
    if (!isFunctionGroupInclude(object) || !isGeneratedInclude(object.name)) return ok(undefined);
    return err(new Error(`${object.name} is generated by SAP (it lists the function group's modules) and cannot be written; write the ${FUNCTION_MODULE.extension} files instead`));
}

/**
 * Explain a failed .asinc write whose name is a function group include's: those live under
 * /functions/groups, and /programs/includes refuses to lock or write them
 */
export function withIncludeHint(object: ObjectRef, error: Error): Error {
    if (object.extension !== PROGRAM_INCLUDE.extension || containerFromIncludeName(object.name) === null) return error;
    return new Error(`${error.message} (if ${object.name} belongs to a function group, save it as ${object.name.toLowerCase()}.${FUNCTION_GROUP_INCLUDE.extension})`);
}
